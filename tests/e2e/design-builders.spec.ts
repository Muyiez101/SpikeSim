import {test,expect} from '@playwright/test';
import {fromCommands} from '../../src/editor/program';

test('builds an FLL robot, edits parts, runs its attachment, and keeps it across field changes',async({page})=>{
  test.setTimeout(150000);
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Build a robot',exact:true}).click();
  const use=page.getByRole('button',{name:'Use this robot',exact:true});
  await expect(use).toBeEnabled({timeout:45000});
  await page.getByLabel('Design name').fill('Student FLL robot');
  const builder=page.frameLocator('iframe[title="Robot design canvas"]');
  await builder.locator('.componentsList li').getByText('Body',{exact:true}).click();
  await builder.locator('.addComponent').click();
  await builder.locator('.selectComponent select').selectOption('Box');
  await builder.getByRole('button',{name:'Ok',exact:true}).click();
  await expect(builder.locator('.componentsList li[componentindex]').filter({hasText:/^Box$/})).toHaveCount(5);
  await use.click();
  const stage=page.locator('.unified-stage');
  await expect(stage).toHaveAttribute('data-status','ready',{timeout:45000});
  await expect(page.getByRole('combobox',{name:'Robot',exact:true})).toHaveValue('custom');
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('spikesim.playground.v1')!).drafts.find((d:{missionId:string})=>d.missionId==='basics-1'));
  const visualProgram=fromCommands([{type:'motor',port:'C',speedPercent:10,durationMs:300},{type:'move',distanceMm:100,speedPercent:40}]);
  await page.getByLabel('Choose a program file').setInputFiles({name:'fll.rlproj',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...saved,schemaVersion:1,kind:'spikesim-program',name:'FLL attachment trial',missionId:null,scene:'worlds/missions/FLL/FLL2025.json?v=00d2ba8a',visualProgram}))});
  await page.getByRole('button',{name:'Open program',exact:true}).click();
  await expect(stage).toHaveAttribute('data-status','ready',{timeout:45000});
  await page.getByRole('button',{name:'Run program',exact:true}).click();
  await expect(stage).toHaveAttribute('data-status','complete',{timeout:20000});
  const child=page.frames().find(f=>f.url().includes('student.html'))!;
  expect(Math.abs(await child.evaluate(()=>{
    const sim=window as unknown as {robot:{components:{type:string;position:number}[]}};
    return sim.robot.components.find(c=>c.type==='ArmActuator')!.position;
  }))).toBeGreaterThan(5);
  await page.getByRole('combobox',{name:'Robot',exact:true}).selectOption('singleFollower');
  await expect(stage).toHaveAttribute('data-status','ready',{timeout:45000});
  await page.getByRole('combobox',{name:'Robot',exact:true}).selectOption('custom');
  await expect(stage).toHaveAttribute('data-status','ready',{timeout:45000});
  await expect(page.getByRole('alert')).toHaveCount(0);expect(errors).toEqual([]);
});

test('edits and saves a ground with an object, survives export/reload, and hides upstream loading UI',async({page})=>{
  test.setTimeout(150000);
  await page.route('**/gears/student.html',async route=>{await new Promise(resolve=>setTimeout(resolve,500));await route.continue();});
  await page.goto('/');
  await expect(page.locator('.unified-loading')).toBeVisible();
  await expect(page.locator('.unified-loading')).toHaveCSS('background-color',/rgb/);
  await expect(page.locator('.unified-stage')).toHaveAttribute('data-status','ready',{timeout:45000});
  const stageFrame=page.frameLocator('iframe[title="3D robot simulator"]');
  await expect(stageFrame.locator('body')).toHaveClass(/student-mode/);
  await expect(stageFrame.locator('body>header')).toBeHidden();
  await page.getByRole('button',{name:'Build a ground',exact:true}).click();
  await expect(page.getByRole('button',{name:'Use this ground',exact:true})).toBeEnabled({timeout:45000});
  const builder=page.frameLocator('iframe[title="Ground design canvas"]');
  await builder.locator('.addObject').click();
  await builder.locator('.selectObject select').selectOption('Box');
  await builder.getByRole('button',{name:'Ok',exact:true}).click();
  await expect(builder.locator('.objectsList li').filter({hasText:/^box$/})).toHaveCount(5);
  const image=await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=1000;canvas.height=600;const ctx=canvas.getContext('2d')!;ctx.fillStyle='#eeeeee';ctx.fillRect(0,0,1000,600);ctx.fillStyle='#222222';ctx.fillRect(100,290,800,20);return canvas.toDataURL('image/png').split(',')[1];});
  await page.getByLabel('Upload ground image').setInputFiles({name:'student-track.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')});
  await expect.poll(()=>builder.locator('body').evaluate(()=>{
    const editor=window as unknown as {builder:{worldOptions:{imageURL:string}}};return editor.builder.worldOptions.imageURL.startsWith('data:image/jpeg');
  })).toBe(true);
  await expect(page.getByRole('button',{name:'Use this ground',exact:true})).toBeEnabled();
  await page.getByLabel('Design name').fill('Our mission ground');
  await page.getByRole('button',{name:'Use this ground',exact:true}).click();
  await expect(page.locator('.unified-stage')).toHaveAttribute('data-status','ready',{timeout:45000});
  const picker=page.getByRole('combobox',{name:'Choose a mission or world'});
  await expect(picker).toHaveValue('custom');
  await page.reload();await expect(picker).toHaveValue('custom');
  await expect(page.locator('.unified-stage')).toHaveAttribute('data-status','ready',{timeout:45000});
  await picker.selectOption('mission:basics-1');
  await expect(page.locator('.unified-stage')).toHaveAttribute('data-status','ready',{timeout:45000});
  await picker.selectOption('custom');
  await expect(page.locator('.unified-stage')).toHaveAttribute('data-status','ready',{timeout:45000});
  await page.getByRole('button',{name:'Export program',exact:true}).click();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Save file',exact:true}).click();
  expect((await download).suggestedFilename()).toContain('.rlproj');
  await expect(page.getByRole('alert')).toHaveCount(0);
});
